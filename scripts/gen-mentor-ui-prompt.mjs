// Generates api/_lib/mentorUiPrompt.ts (the OpenUI system prompt for the Mentor) from
// src/mentorUiLibrary.tsx. Run: npm run gen:mentor-ui   — and commit the result.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const out = join(process.cwd(), 'node_modules', '.cache', 'mentor-ui-gen');
mkdirSync(out, { recursive: true });
const outfile = join(out, 'lib.mjs');
await build({
  entryPoints: [resolve('src/mentorUiLibrary.tsx')],
  bundle: true, format: 'esm', platform: 'node', outfile, logLevel: 'silent', jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime', '@openuidev/react-lang', 'zod', 'zod/v4'],
});
const { mentorUiLibrary, MENTOR_UI_PROMPT_OPTIONS } = await import(pathToFileURL(outfile).href);
const prompt = mentorUiLibrary.prompt(MENTOR_UI_PROMPT_OPTIONS);
writeFileSync(
  'api/_lib/mentorUiPrompt.ts',
  `// AUTO-GENERATED by scripts/gen-mentor-ui-prompt.mjs from src/mentorUiLibrary.tsx — do not edit by hand.\n// Re-run \`npm run gen:mentor-ui\` after changing the library.\nexport const MENTOR_UI_PROMPT = ${JSON.stringify(prompt)};\n`
);
console.log('wrote api/_lib/mentorUiPrompt.ts', prompt.length, 'chars');
